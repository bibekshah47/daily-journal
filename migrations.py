def applied_versions(connection):
    """Versions recorded in schema_migrations (empty if the table is missing)."""
    if connection.is_postgres:
        exists = connection.fetchone("SELECT to_regclass('schema_migrations')")[0]
    else:
        exists = connection.fetchone(
            "SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = 'schema_migrations'")
    if not exists:
        return set()
    return {row[0] for row in connection.fetchall("SELECT version FROM schema_migrations")}


def migrate(target, now=None):
    """Run every pending migration on the database at `target`. Returns the
    versions applied (empty when the schema was already up to date)."""
    connection = connect(target)
    try:
        if not connection.is_postgres and _is_pre_migration_sqlite(connection):
            # A journal file from before migrations existed: bring any older
            # layout up to migration 1's schema first (a no-op for a file
            # that is already current). It is then recorded as version 1.
            _upgrade_pre_migration_sqlite(connection)

        if connection.is_postgres:
            connection.execute("SELECT pg_advisory_xact_lock(?)", (ADVISORY_LOCK_KEY,))
        else:
            connection.execute("BEGIN IMMEDIATE")
        connection.execute(SCHEMA_MIGRATIONS_TABLE)
        applied = applied_versions(connection)
        stamp = (now or utc_now()).isoformat(timespec="seconds")

        if not applied and not connection.is_postgres and _has_journal_tables(connection):
            connection.execute(
                "INSERT INTO schema_migrations (version, applied_at) VALUES (1, ?)", (stamp,))
            applied.add(1)

        done = []
        for migration in MIGRATIONS:
            if migration.version in applied:
                continue
            statements = migration.postgres if connection.is_postgres else migration.sqlite
            for statement in statements:
                connection.execute(statement)
            connection.execute("INSERT INTO schema_migrations (version, applied_at) VALUES (?, ?)",
                               (migration.version, stamp))
            done.append(migration.version)
        connection.commit()
        return done
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


# ---------- SQLite files from before migrations ----------
#
# Until migrations.py existed, every request checked the tables with PRAGMA
# table_info and added whatever was missing. That upgrade is kept here, for
# SQLite only, so an old journal file (even one from before accounts) still
# opens: it is run once, then the file is recorded as version 1.

def _sqlite_tables(connection):
    return {row[0] for row in connection.fetchall(
        "SELECT name FROM sqlite_master WHERE type = 'table'")}


def _has_journal_tables(connection):
    return bool({"users", "entries"} & _sqlite_tables(connection))


def _is_pre_migration_sqlite(connection):
    tables = _sqlite_tables(connection)
    return "schema_migrations" not in tables and bool({"users", "entries"} & tables)


_OLD_TAGS_TABLE = """
    CREATE TABLE IF NOT EXISTS {name} (
        id INTEGER PRIMARY KEY,
        user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
        name TEXT NOT NULL,
        UNIQUE (user_id, name)
    )
"""

_OLD_USERS_TABLE = """
    CREATE TABLE IF NOT EXISTS {name} (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        email TEXT NOT NULL UNIQUE,
        password_hash TEXT NOT NULL,
        created_at TEXT NOT NULL,
        display_name TEXT,
        session_version INTEGER NOT NULL DEFAULT 0,
        password_changed_at TEXT
    )
"""
_USER_COLUMNS = ("id, email, password_hash, created_at, display_name, session_version, "
                 "password_changed_at")


def _columns(connection, table):
    # Fixed table names only.
    return {row[1] for row in connection.fetchall(f"PRAGMA table_info({table})")}


def _tags_need_rebuild(connection):
    """True for a tags table from before accounts (global UNIQUE(name))."""
    columns = _columns(connection, "tags")
    return bool(columns) and "user_id" not in columns


def _rebuild_tags_per_user(connection):
    """Swap the global UNIQUE(name) for UNIQUE(user_id, name), keeping every
    id so entry_tags still points at the right tags. Existing tags get
    user_id NULL until `flask assign-entries` gives them an owner."""
    links_before = connection.fetchone("SELECT COUNT(*) FROM entry_tags")[0]
    tags_before = connection.fetchone("SELECT COUNT(*) FROM tags")[0]
    connection.execute(_OLD_TAGS_TABLE.format(name="tags_per_user"))
    connection.execute(
        "INSERT INTO tags_per_user (id, user_id, name) SELECT id, NULL, name FROM tags")
    connection.execute("DROP TABLE tags")
    connection.execute("ALTER TABLE tags_per_user RENAME TO tags")
    links_after = connection.fetchone("SELECT COUNT(*) FROM entry_tags")[0]
    tags_after = connection.fetchone("SELECT COUNT(*) FROM tags")[0]
    if (links_before, tags_before) != (links_after, tags_after):
        raise RuntimeError("Tag upgrade lost rows; nothing was changed.")


def _users_need_rebuild(connection):
    """True for a users table whose ids can be reused (no AUTOINCREMENT)."""
    row = connection.fetchone(
        "SELECT sql FROM sqlite_master WHERE type = 'table' AND name = 'users'")
    return row is not None and "AUTOINCREMENT" not in row[0].upper()


def _rebuild_users_autoincrement(connection):
    before = connection.fetchone("SELECT COUNT(*) FROM users")[0]
    connection.execute(_OLD_USERS_TABLE.format(name="users_autoincrement"))
    connection.execute(f"INSERT INTO users_autoincrement ({_USER_COLUMNS}) "
                       f"SELECT {_USER_COLUMNS} FROM users")
    connection.execute("DROP TABLE users")
    connection.execute("ALTER TABLE users_autoincrement RENAME TO users")
    if connection.fetchone("SELECT COUNT(*) FROM users")[0] != before:
        raise RuntimeError("User upgrade lost rows; nothing was changed.")


def _upgrade_pre_migration_sqlite(connection):
    # The table rebuilds must run with foreign keys off (DROP TABLE would
    # otherwise cascade), and SQLite only changes that outside a transaction.
    rebuild = _tags_need_rebuild(connection) or _users_need_rebuild(connection)
    if rebuild:
        connection.execute("PRAGMA foreign_keys = OFF")
    try:
        with connection:
            connection.execute("BEGIN IMMEDIATE")
            connection.execute(_OLD_USERS_TABLE.format(name="users"))
            for name, definition in (("display_name", "TEXT"),
                                     ("session_version", "INTEGER NOT NULL DEFAULT 0"),
                                     ("password_changed_at", "TEXT")):
                if name not in _columns(connection, "users"):
                    connection.execute(f"ALTER TABLE users ADD COLUMN {name} {definition}")
            if _users_need_rebuild(connection):
                _rebuild_users_autoincrement(connection)
            connection.execute("""
                CREATE TABLE IF NOT EXISTS entries (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    content TEXT NOT NULL,
                    created_at TEXT NOT NULL,
                    mood TEXT
                )
            """)
            columns = _columns(connection, "entries")
            for name, definition in (
                    ("content_html", "TEXT"), ("title", "TEXT"),
                    ("is_favorite", "INTEGER NOT NULL DEFAULT 0"),
                    ("went_well", "TEXT"), ("went_wrong", "TEXT"),
                    ("improve_tomorrow", "TEXT"), ("deleted_at", "TEXT"),
                    ("user_id", "INTEGER REFERENCES users(id) ON DELETE CASCADE")):
                if name not in columns:
                    connection.execute(f"ALTER TABLE entries ADD COLUMN {name} {definition}")
            if _tags_need_rebuild(connection):
                _rebuild_tags_per_user(connection)
            else:
                connection.execute(_OLD_TAGS_TABLE.format(name="tags"))
            connection.execute("""
                CREATE TABLE IF NOT EXISTS entry_tags (
                    entry_id INTEGER NOT NULL REFERENCES entries(id) ON DELETE CASCADE,
                    tag_id INTEGER NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
                    PRIMARY KEY (entry_id, tag_id)
                )
            """)
            for statement in _VIEW_AND_INDEXES + [_LOGIN_THROTTLE]:
                connection.execute(statement.replace("CREATE VIEW", "CREATE VIEW IF NOT EXISTS")
                                   .replace("CREATE INDEX", "CREATE INDEX IF NOT EXISTS")
                                   .replace("CREATE TABLE", "CREATE TABLE IF NOT EXISTS"))
    finally:
        if rebuild:
            connection.execute("PRAGMA foreign_keys = ON")
